void	ft_striteri(char *s, void (*f)(unsigned int, char *))
{
	size_t	i;

	i = 0;
	if (!s || !f)
		return (NULL);
	while (s[i])
	{
		s[i++] = (*f)(i, &str[i]);
	}
}
